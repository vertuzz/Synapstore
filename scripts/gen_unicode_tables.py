#!/usr/bin/env python3
"""Generate src/embed/bert/unicode.dat: the Unicode properties the BERT
tokenizer needs (punctuation, nonspacing marks, "other" chars dropped by
clean_text, space separators and accent-stripping decompositions).
Usage: python3 scripts/gen_unicode_tables.py > src/embed/bert/unicode.dat"""
import sys, unicodedata

LIMIT = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(LIMIT + 1):
        ok = cp < LIMIT and pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append(f"{start:x}-{cp - 1:x}" if cp - 1 > start else f"{start:x}")
            start = None
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


def strip(cp):
    d = unicodedata.normalize("NFD", chr(cp))
    return "".join(c for c in d if unicodedata.category(c) != "Mn")


lines = [f"# generated by scripts/gen_unicode_tables.py (unicodedata {unicodedata.unidata_version})"]
for name, pred in [
    ("P", lambda c: cat(c).startswith("P")),
    ("Mn", lambda c: cat(c) == "Mn"),
    ("C", lambda c: cat(c) in ("Cc", "Cf", "Co", "Cn")),
    ("Zs", lambda c: cat(c) == "Zs"),
]:
    lines.append(name + " " + " ".join(ranges(pred)))
dec = []
for cp in range(LIMIT):
    if 0xAC00 <= cp <= 0xD7A3 or cat(cp) == "Mn":
        continue  # Hangul is decomposed algorithmically; marks are dropped
    s = strip(cp)
    if s != chr(cp):
        dec.append(f"{cp:x}:" + ".".join(f"{ord(c):x}" for c in s))
for i in range(0, len(dec), 16):
    lines.append("D " + " ".join(dec[i:i + 16]))
sys.stdout.write("\n".join(lines) + "\n")
